# ---------- 6. Anion gap ----------
def _stack(x, segs, k, base, w=44):
    out, y = [], base
    for v, c, lab in segs:
        h = v * k
        out.append(rect(x, y - h, w, h, c, 2))
        if lab:
            ls = lab.split("\n")
            out.append(t(x + w / 2, y - h / 2 + 4 - (len(ls) - 1) * 6, lab, "xs mid b", lh=1.15))
        y -= h
    return out


