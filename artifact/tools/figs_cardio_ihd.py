# ---------- ตัวช่วย ----------
def _f(v):
    v = round(float(v), 1)
    return str(int(v)) if v == int(v) else str(v)


def _beat(x, y, st=0, T=9, q=0, r=28, s=6, k=1.0, tw=14, c="ln w2"):
    """คลื่น ECG หนึ่งตัว (กว้าง ~ (48+tw)·k) · st บวก = ST ยก · T ลบ = T หัวกลับ"""
    P = lambda dx, dy: "%s %s" % (_f(x + dx * k), _f(y + dy * k))
    d = ("M" + P(0, 0) + " L" + P(8, 0) + " Q" + P(11, -6) + " " + P(14, 0) + " L" + P(19, 0) +
         " L" + P(21, 2 + q) + " L" + P(24, -r) + " L" + P(28, s) + " L" + P(31, -st) + " L" + P(38, -st) +
         " Q" + P(38 + tw / 2, -st - 2 * T) + " " + P(38 + tw, 0) + " L" + P(48 + tw, 0))
    return path(d, c)


def _plot(pts, X, Y, c):
    return poly([(X(a), Y(b)) for a, b in pts], c)


