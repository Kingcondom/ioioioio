def _fascicle(cx, cy, dm):
    import math
    out = [circ(cx, cy, 78, "sk")]
    pts = []
    for i in range(-4, 5):
        for j in range(-4, 5):
            x = cx + 21 * i + (10.5 if j % 2 else 0)
            y = cy + 18.5 * j
            d = math.hypot(x - cx, y - cy)
            if d < 64:
                pts.append((x, y, d))
    for k, (x, y, d) in enumerate(pts):
        if dm and d > 44:
            out.append(circ(x, y, 6.5, "ms"))
        elif not dm and k in (12, 30):
            out.append(circ(x, y, 9.5, "bad"))
            out += [circ(x + 11 * math.cos(a), y + 11 * math.sin(a), 2.6, "inkf") for a in (0.3, 1.5, 2.6, 3.8, 5.0)]
        else:
            out.append(circ(x, y, 9.5, "bx"))
    if dm:
        for a in range(0, 360, 45):
            r = math.radians(a + 20)
            x, y = cx + 78 * math.cos(r), cy + 78 * math.sin(r)
            out += [circ(x, y, 4, "bad"), circ(x + 3, y - 3, 2, "inkf")]
        out += [circ(cx - 92, cy - 50, 9, "bad")]
        out += [circ(cx - 92 + dx, cy - 50 + dy, 2.6, "inkf") for dx, dy in ((-14, -4), (-12, 8), (12, 6), (2, 14), (-4, -15), (12, -8))]
    else:
        for x, y, d in pts[::3]:
            out.append(circ(x + 10, y + 9, 2.4, "inkf"))
    return out


