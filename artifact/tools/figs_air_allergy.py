def _ab(x, y, ang=0, c="lac w2", s=1.0):
    """antibody รูปตัว Y — (x,y) = ปลายก้าน · ang = ทิศที่แขนชี้ (องศา, 90 = ขึ้น)"""
    a = math.radians(ang)
    ux, uy = math.cos(a), -math.sin(a)
    L, A = 9 * s, 7 * s
    jx, jy = x + ux * L, y + uy * L
    out = line(x, y, jx, jy, c)
    for d in (35, -35):
        b = math.radians(ang + d)
        out += line(jx, jy, jx + math.cos(b) * A, jy - math.sin(b) * A, c)
    return out


def _igm(cx, cy, r=12, c="lms w2"):
    out = circ(cx, cy, 3.5, "msf")
    for k in range(5):
        a = math.radians(90 + 72 * k)
        out += line(cx + math.cos(a) * 3, cy - math.sin(a) * 3, cx + math.cos(a) * r, cy - math.sin(a) * r, c)
    return out


def _granules(cx, cy, pts, cls="inkf", r=2.4):
    return "".join(circ(cx + dx, cy + dy, r, cls) for dx, dy in pts)


