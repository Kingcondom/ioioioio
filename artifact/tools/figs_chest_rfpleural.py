def _sev(p):
    if p <= 0: return 0.0
    return 1 / (23400 / (p ** 3 + 150 * p) + 1)


def _rand(n, seed=7):
    out, s = [], seed
    for _ in range(n):
        s = (s * 1103515245 + 12345) % 2147483648
        out.append(s / 2147483648)
    return out


