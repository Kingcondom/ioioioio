def _arc(cx, cy, r, a1, a2, c):
    p = lambda a: (cx + r * math.sin(math.radians(a)), cy - r * math.cos(math.radians(a)))
    (x1, y1), (x2, y2) = p(a1), p(a2)
    large = 1 if (a2 - a1) % 360 > 180 else 0
    return path("M%.1f %.1f A%d %d 0 %d 1 %.1f %.1f" % (x1, y1, r, r, large, x2, y2), c)


