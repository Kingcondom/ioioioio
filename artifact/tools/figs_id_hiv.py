def _num(x, y, n, c="ac", tc="tac"):
    return circ(x, y, 9, c) + t(x, y + 4, n, "xs b mid " + tc)


def _virus(cx, cy, r=18, c="ac"):
    out = [circ(cx, cy, r, c)]
    for k in range(8):
        a = math.radians(k * 45 + 10)
        out += [line(cx + r * math.cos(a), cy + r * math.sin(a), cx + (r + 5) * math.cos(a), cy + (r + 5) * math.sin(a), "lac"),
                circ(cx + (r + 6) * math.cos(a), cy + (r + 6) * math.sin(a), 2.2, "acf")]
    out.append(path("M%.1f %.1f q4 -6 8 0 q4 6 8 0" % (cx - 8, cy), "lbad w2"))
    return "".join(out)


