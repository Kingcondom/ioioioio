def _down(x, y1, y2, c="ln", m="ah"):
    return line(x, y1, x, y2 - 2, c, m)


def _tee(x1, y1, x2, y2, c="lbad w2"):
    """เส้นยับยั้ง ปลายเป็นขีดตั้งฉาก"""
    dx, dy = x2 - x1, y2 - y1
    L = math.hypot(dx, dy) or 1
    px, py = -dy / L * 7, dx / L * 7
    return line(x1, y1, x2, y2, c) + line(x2 - px, y2 - py, x2 + px, y2 + py, c)


def _hub(c1, c2, items, ccls="ac", h=350):
    """วงกลางเชื่อมกล่องซ้าย 3 ขวา 3 · items = [(cls, text)] เรียง ซ้ายบน ขวาบน ซ้ายกลาง ..."""
    cx, cy = 210, h / 2 - 6
    out = []
    for k, (c, s) in enumerate(items):
        left = k % 2 == 0
        x = 6 if left else 268
        y = 14 + (k // 2) * ((h - 40) / 3)
        bh = (h - 40) / 3 - 16
        out.append(box(x, y, 146, bh, c, s, fs=11))
        ex, ey = (x + 146, y + bh / 2) if left else (x, y + bh / 2)
        dx, dy = ex - cx, ey - cy
        k2 = 1 / math.sqrt((dx / 58) ** 2 + (dy / 36) ** 2)
        out.append(line(cx + dx * k2, cy + dy * k2, ex + (3 if left else -3), ey, "lmu"))
    out = [ell(cx, cy, 58, 36, ccls), t(cx, cy - 8, c1, "b mid"), t(cx, cy + 9, c2, "xs mid", 1.2)] + out
    return out


