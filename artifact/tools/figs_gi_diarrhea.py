def dia_bristol():
    shapes = []
    y0 = 18
    rows = [("1", "ก้อนกลมแข็งแยกกัน", "bad"), ("2", "ก้อนแข็งจับเป็นลำ", "bad"), ("3", "ลำ ผิวแตกร้าว", "ok"),
            ("4", "ลำนิ่ม ผิวเรียบ", "ok"), ("5", "ก้อนนิ่ม ขอบชัด", "ok"), ("6", "เละ ขอบไม่ชัด", "ms"), ("7", "เป็นน้ำ", "ms")]
    for i, (n, label, c) in enumerate(rows):
        y = y0 + i * 40
        shapes.append(circ(28, y + 14, 12, c))
        shapes.append(t(28, y + 18, n, "sm mid b"))
        x = 52
        if n == "1":
            for k in range(5): shapes.append(circ(x + 10 + k * 22, y + 14, 8, "inkf"))
        elif n == "2":
            shapes.append(rect(x, y + 4, 110, 20, "inkf", 10))
            for k in range(6): shapes.append(circ(x + 8 + k * 19, y + 6, 6, "inkf"))
        elif n == "3":
            shapes.append(rect(x, y + 4, 110, 20, "inkf", 10))
            for k in range(4): shapes.append(line(x + 20 + k * 22, y + 6, x + 26 + k * 22, y + 14, "lru w2"))
        elif n == "4":
            shapes.append(rect(x, y + 4, 120, 20, "inkf", 10))
        elif n == "5":
            for k in range(3): shapes.append(rect(x + k * 40, y + 6, 32, 16, "inkf", 8))
        elif n == "6":
            for k in range(4): shapes.append(ell(x + 14 + k * 30, y + 14, 14, 7, "muf"))
        else:
            shapes.append(path("M%d %d q20 -10 40 0 t40 0 t40 0" % (x, y + 16), "lmu w3"))
        shapes.append(t(190, y + 18, label, "sm"))
    shapes += [brace(320, 18, 92, "lbad", 1), t(338, 60, "ท้องผูก", "sm b tbad"),
               brace(320, 98, 212, "lok", 1), t(338, 160, "ปกติ", "sm b tok"), t(338, 176, "(4 ดีที่สุด)", "xs tok"),
               brace(320, 218, 292, "lms", 1), t(338, 260, "ท้องเสีย", "sm b tms")]
    return fig("Bristol Stool Form Scale",
               "แบบ **1–2 = ท้องผูก** · **3–5 ปกติ** (4 ดีที่สุด) · **6–7 = ท้องเสีย** — ใช้ทั้งนิยามท้องเสียและแบ่ง **subtype ของ IBS** "
               "(นับสัดส่วนวันที่ถ่ายเป็นแบบ 1–2 หรือ 6–7 ที่ 25%)",
               svg(420, 300, "Bristol stool scale เจ็ดแบบ แบบหนึ่งถึงสองท้องผูก สามถึงห้าปกติ หกถึงเจ็ดท้องเสีย", *shapes))


