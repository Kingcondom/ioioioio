def _down(x, y1, y2, c="ln", m="ah"):
    return line(x, y1, x, y2 - 2, c, m)


def _tee(x1, y1, x2, y2, c="lbad w2"):
    """เส้นยับยั้ง (ปลายเป็นขีดตั้งฉาก)"""
    import math
    dx, dy = x2 - x1, y2 - y1
    L = math.hypot(dx, dy) or 1
    px, py = -dy / L * 7, dx / L * 7
    return line(x1, y1, x2, y2, c) + line(x2 - px, y2 - py, x2 + px, y2 + py, c)


