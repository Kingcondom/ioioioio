def ptb_granuloma():
    cx, cy = 128, 150
    out = [circ(cx, cy, 100, "sk"), circ(cx, cy, 100, "lru w3")]
    for k in range(24):
        a = math.radians(k * 15 + 7)
        out.append(circ(cx + 86 * math.cos(a), cy + 86 * math.sin(a), 4.2, "inkf"))
        a2 = math.radians(k * 15)
        out.append(circ(cx + 76 * math.cos(a2 + 0.13), cy + 76 * math.sin(a2 + 0.13), 3.2, "inkf") if k % 2 else "")
    for k in range(14):
        a = k * 360 / 14
        if k in (2, 9): continue
        r = math.radians(a)
        out.append(ell(cx + 58 * math.cos(r), cy + 58 * math.sin(r), 11, 5.5, "ac", a + 90))
    for a in (40, 250):
        r = math.radians(a)
