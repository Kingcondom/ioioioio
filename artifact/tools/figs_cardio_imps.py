def _card(x, y, w, h, c, title, lines, tc="", lh=16):
    out = [rect(x, y, w, h, c, 8), t(x + 10, y + 19, title, ("sm b " + tc).strip())]
    out += [t(x + 10, y + 19 + lh * (k + 1), s, "xs i2") for k, s in enumerate(lines)]
    return "".join(out)


def _inh(x1, y, x2, c="lok"):
    """เส้นยับยั้ง (ปลายเป็นขีดตั้ง) จาก x1 ไป x2 ที่ระดับ y"""
    return line(x1, y, x2, y, c + " w2") + line(x2, y - 8, x2, y + 8, c + " w3")


def _sector(cx, cy, r1, r2, a1, a2, c):
    """ส่วนของวงแหวน r1–r2 จากมุม a1 ถึง a2 (องศา · 0 = 3 นาฬิกา · หมุนตามเข็ม)"""
    p = lambda r, a: (cx + r * math.cos(math.radians(a)), cy + r * math.sin(math.radians(a)))
    (x1, y1), (x2, y2), (x3, y3), (x4, y4) = p(r2, a1), p(r2, a2), p(r1, a2), p(r1, a1)
    big = 1 if (a2 - a1) % 360 > 180 else 0
    return path("M%.1f %.1f A%s %s 0 %d 1 %.1f %.1f L%.1f %.1f A%s %s 0 %d 0 %.1f %.1f Z" % (
        x1, y1, r2, r2, big, x2, y2, x3, y3, r1, r1, big, x4, y4), c)


def _beat(x, y, st=0, pr=0, kind="concave", amp=34):
    """ECG หนึ่งจังหวะ กว้าง 90 · st บวก = ยกขึ้น · pr บวก = กดลง"""
    d = "M%s %s L%s %s Q%s %s %s %s" % (x, y, x + 6, y, x + 12, y - 9, x + 18, y)
    d += " L%s %s L%s %s" % (x + 19, y + pr, x + 28, y + pr)
    d += " L%s %s L%s %s L%s %s L%s %s" % (x + 31, y + pr + 4, x + 35, y - amp, x + 39, y + 8, x + 42, y - st)
    if kind == "concave":
        d += " Q%s %s %s %s Q%s %s %s %s" % (x + 52, y - st + 2, x + 60, y - st - 6, x + 68, y - st - 24, x + 77, y)
    elif kind == "convex":
        d += " Q%s %s %s %s Q%s %s %s %s" % (x + 50, y - st - 14, x + 62, y - st - 9, x + 70, y - st - 4, x + 78, y)
    else:  # ST กด
        d += " L%s %s Q%s %s %s %s Q%s %s %s %s" % (x + 54, y - st, x + 60, y - st, x + 64, y - 4, x + 70, y - 12, x + 78, y)
    d += " L%s %s" % (x + 90, y)
    return line(x, y, x + 90, y, "lru da") + path(d, "ln w2")


def _vent(cx, cy, sep, rv_w):
    """RV (ซ้ายภาพ) + LV (ขวาภาพ) · sep = ผนังกั้นยื่นเข้า LV เท่าไร · rv_w = ความกว้าง RV"""
    sx = cx + sep
    lv = "M%s %s Q%s %s %s %s Q%s %s %s %s Q%s %s %s %s Z" % (
        sx, cy - 34, cx + 64, cy - 44, cx + 66, cy, cx + 64, cy + 44, sx, cy + 34, sx + 16, cy, sx, cy - 34)
    rv = "M%s %s Q%s %s %s %s Q%s %s %s %s Q%s %s %s %s Q%s %s %s %s Z" % (
        sx, cy - 34, sx + 16, cy, sx, cy + 34, cx - rv_w * 0.4, cy + 52, cx - rv_w, cy + 24,
        cx - rv_w - 16, cy, cx - rv_w, cy - 24, cx - rv_w * 0.4, cy - 52, sx, cy - 34)
    return path(rv, "wa") + path(lv, "bad")


