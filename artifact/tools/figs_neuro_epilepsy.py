def _wave(x0, y0, w, f, step=1.5, c="ln"):
    pts, x = [], 0.0
    while x <= w:
        pts.append((x0 + x, y0 + f(x)))
        x += step
    return poly(pts, c)


def _noise(x, a=1.0):
    return a * (2.2 * math.sin(x * 0.55) + 1.4 * math.sin(x * 1.37 + 1.1) + 0.8 * math.sin(x * 2.9 + 0.4))


def _spike(x, at, h=20):
    d = x - at
    if 0 <= d < 3: return -h * d / 3
    if 3 <= d < 7: return -h + (h + 5) * (d - 3) / 4
    if 7 <= d < 18: return 5 - 5 * (d - 7) / 11 + 0 * d
    return 0


def _sw(x, P, h=22, wv=12):
    d = x % P
    if d < 3: return -h * d / 3
    if d < 6: return -h + (h + 5) * (d - 3) / 3
    return 5 * (1 - (d - 6) / (P - 6)) - wv * math.sin(math.pi * (d - 6) / (P - 6))


