def _p(cx, cy, r, deg, ry=None):
    a = math.radians(deg)
    return cx + r * math.cos(a), cy - (ry if ry is not None else r) * math.sin(a)


def _arc(cx, cy, rx, ry, a1, a2, c):
    """เส้นโค้งวงรีจากมุม a1 ถึง a2 (องศา ทวนเข็มทางคณิต)"""
    x1, y1 = _p(cx, cy, rx, a1, ry)
    x2, y2 = _p(cx, cy, rx, a2, ry)
    return path("M%.1f %.1f A%s %s 0 %d 0 %.1f %.1f" % (x1, y1, rx, ry, 1 if a2 - a1 > 180 else 0, x2, y2), c)


def _sector(cx, cy, r1, r2, a1, a2, c):
    o1, o2 = _p(cx, cy, r2, a1), _p(cx, cy, r2, a2)
    i1, i2 = _p(cx, cy, r1, a1), _p(cx, cy, r1, a2)
    return path("M%.1f %.1f A%s %s 0 0 0 %.1f %.1f L%.1f %.1f A%s %s 0 0 1 %.1f %.1f Z" % (
        o1[0], o1[1], r2, r2, o2[0], o2[1], i2[0], i2[1], r1, r1, i1[0], i1[1]), c)


