def _ct(cx, cy, kind):
    out = [circ(cx, cy, 52, "bx")]
    wedge = "M%d %d L%.1f %.1f A52 52 0 0 0 %.1f %.1f Z" % ((cx - 10, cy) + _p(cx, cy, 52, 140) + _p(cx, cy, 52, 220))
    if kind == 0:
        out += [path(wedge, "lms da"), line(cx - 10, cy + 2, cx - 32, cy + 6, "lbad w5"),
                line(cx, cy - 48, cx, cy + 48, "lru da")]
    elif kind == 1:
        out += [path(wedge, "ms"), path("M%d %d Q%d %d %d %d" % (cx, cy - 50, cx + 12, cy, cx, cy + 50), "lru da"),
                ell(cx + 16, cy - 2, 6, 12, "sk")]
    elif kind == 2:
        out += [path("M%d %d L%.1f %.1f A52 52 0 0 0 %.1f %.1f Z" % ((cx - 18, cy) + _p(cx, cy, 52, 155) + _p(cx, cy, 52, 205)), "sk"),
                line(cx, cy - 48, cx, cy + 48, "lru da"), ell(cx - 12, cy - 2, 9, 16, "sk"), ell(cx + 10, cy - 2, 5, 12, "sk")]
    else:
        out += [line(cx, cy - 48, cx, cy + 48, "lru da"), ell(cx - 22, cy + 4, 14, 11, "badf")]
    return out


