def _c(fn, X, Y, n=60):
    return [(X(i / n), Y(fn(i / n))) for i in range(n + 1)]


def _colon(x, segs, base="lru w5"):
    """ลำไส้ใหญ่รูปกรอบ · segs = รายการ (a, b, cls) ช่วงตามความยาว 0 (caecum) ถึง 1 (rectum)"""
    pts = [(x + 30, 150), (x + 30, 40), (x + 160, 40), (x + 160, 130), (x + 130, 160), (x + 100, 160), (x + 100, 190)]
    seg = [math.dist(pts[i], pts[i + 1]) for i in range(len(pts) - 1)]
    L = sum(seg)
    def at(u):
        d = u * L
        for i, s in enumerate(seg):
            if d <= s: return (pts[i][0] + (pts[i + 1][0] - pts[i][0]) * d / s, pts[i][1] + (pts[i + 1][1] - pts[i][1]) * d / s)
            d -= s
        return pts[-1]
    out = [poly(pts, base)]
    for a, b, c in segs:
        out.append(poly([at(a + (b - a) * i / 30) for i in range(31)], c))
    return out


